// HeartbeatInfo configures RFC 4666 M3UA BEAT/BEAT Ack liveness.
//
// It does not configure SCTP HEARTBEAT chunks or SCTP path-management timers;
// those stay in the SCTP transport stack. This package uses HeartbeatInfo only
// for application-layer ASPSM BEAT messages after the ASP reaches ASP-ACTIVE.
type HeartbeatInfo struct {
	// Enabled turns on the managed M3UA BEAT loop.
	Enabled bool
	// Interval is T(beat), the delay before sending the next M3UA BEAT.
	Interval time.Duration
	// Timer is the M3UA liveness deadline for a BEAT round. Zero resolves to
	// 2*T(beat), per RFC 4666 Section 4.3.4.6.
	Timer time.Duration
}

// NewHeartbeatInfo creates M3UA BEAT configuration.
//
// The managed BEAT loop generates fresh Heartbeat Data for every transmitted
// M3UA BEAT, so there is no caller-supplied value: RFC 4666 Section 3.5.5 has
// the peer echo the parameter, and matching the echo against freshly generated
// data is what makes a BEAT Ack identifiable and a replayed one detectable.
func NewHeartbeatInfo(interval, timer time.Duration) *HeartbeatInfo {
	return &HeartbeatInfo{Enabled: true, Interval: interval, Timer: timer}
}

// SCTPSACKInfo configures the SCTP delayed-SACK timer.
//
// SackDelay sack_delay: This parameter contains the number of milliseconds the
// user is requesting that the delayed SACK timer be set to.
//
// RFC 9260 Section 6.2 — the current SCTP specification, which obsoleted
// RFC 4960 — bounds it from above only: "An implementation MUST NOT allow the
// maximum delay (protocol parameter 'SACK.Delay') to be configured to be more
// than 500 ms. In other words, an implementation MAY lower the value of
// 'SACK.Delay' below 500 ms but MUST NOT raise it above 500 ms." The 200 ms in
// the same section is when an acknowledgement SHOULD be generated by, not a
// floor, so any value up to 500 is permitted and zero disables the delay.
// A larger value is refused when the association is set up; see
// ErrSackDelayTooLarge.
//
// SackFrequency sack_freq: This parameter contains the number of packets that must
// be received before a SACK is sent without waiting for the delay
// timer to expire.  The default value is 2; setting this value to 1
// will disable the delayed SACK algorithm.
type SCTPSACKInfo struct {
	Enabled       bool
	SackDelay     uint32
	SackFrequency uint32
}

// SCTPNoDelayInfo is a set of information for SCTP NODELAY configuration.
//
// NoDelay, when true, disables the Nagle-like bundling algorithm so that
// user messages are sent as soon as possible (SCTP_NODELAY = 1). When
// false, small messages may be bundled to improve throughput.
type SCTPNoDelayInfo struct {
	Enabled bool
	NoDelay bool
}

// DefaultReadBufferSize is the read buffer size used when SCTPConfig
// leaves ReadBufferSize unset.
//
// 64 KiB accommodates any M3UA message in practical use — SS7 traffic
// interworked at an SG is capped at a 272-octet SIF, and even the larger blocks
// M3UA permits natively stay far below this — while costing one allocation per
// association rather than per read.
const DefaultReadBufferSize = 65535

// SCTPConfig holds all SCTP-related configuration parameters.
// This separates SCTP layer configuration from M3UA layer configuration.
//
// An AssociationConfig — and therefore its SCTPConfig — may be shared by every
// association a Listener
// accepts, and by repeated Dials. It therefore holds settings only: the
// SCTP association and everything derived from it belong to the Association.
type SCTPConfig struct {
	*SCTPSACKInfo
	*SCTPNoDelayInfo

	// InitTimeout bounds Dial's one-shot SCTP association attempt. Zero
	// selects DefaultInitTimeout.
	InitTimeout time.Duration

	// ReadBufferSize is the size of the buffer each read from the association
	// is made into. Zero selects DefaultReadBufferSize.
	//
	// SCTP reassembles a fragmented message before delivering it, so this is
	// not an MTU: it must accommodate the largest single M3UA message a peer
	// may send. RFC 4666 Section 1.3.2.1 is explicit that "The M3UA layer does
	// not impose a 272-octet signalling information field (SIF) length limit
	// as specified by the SS7 MTP Level 2 protocol [...]. Larger information
	// blocks can be accommodated directly by M3UA/SCTP", and the message length
	// field
	// is 32-bit, so there is no protocol-level maximum to size against. Raise
	// this if a peer is known to send larger blocks than the default allows.
	ReadBufferSize int

	// SocketReceiveBuffer is the SO_RCVBUF size, in bytes, requested for the
	// association's SCTP socket. Zero leaves the size the socket starts with:
	// the kernel default for Dial and Listen, and the listening socket's for an
	// association Accept returns, which inherits it.
	//
	// It is not ReadBufferSize. That bounds one M3UA message read out of the
	// socket; this is the kernel queue those reads drain, where DATA waits
	// until the application reads it.
	//
	// It is applied before the socket connects or listens, which is what makes
	// it matter: RFC 6458 Section 8.1.6 has SO_RCVBUF control the receiver
	// window on a one-to-one socket, and the INIT or INIT ACK announces that
	// window as the Advertised Receiver Window Credit, "the dedicated buffer
	// space [...] reserved in association with this window" (RFC 9260
	// Sections 3.3.2 and 3.3.3). Linux fixes it when the association is
	// created and announces half the socket's buffer. A size applied afterwards
	// changes the buffer and not the window the peer was given.
	//
	// socket(7) describes what Linux does with the request: it caps it at
	// net.core.rmem_max and then doubles it for bookkeeping overhead, so the
	// socket gets twice the smaller of the two. A socket left unset gets
	// net.core.rmem_default as it is, undoubled, and the cap applies even where
	// rmem_default is the larger, so on such a host a request can leave the
	// socket smaller than the default did: with rmem_default at 16 MiB and
	// rmem_max at 4 MiB, a request of 8 MiB gives an 8 MiB buffer and a 4 MiB
	// window where leaving it unset gave 16 MiB and 8 MiB. Compare
	// Association.SocketReceiveBuffer, which reports the size that took effect,
	// with what an unset socket reports. The library never uses SO_RCVBUFFORCE
	// to exceed the cap; raising the cap is the operator's decision.
	//
	// A Listener applies its DefaultAssociationConfig's value to the listening
	// socket when Listen is called, and an accepted association's receive size
	// can only come from there; see ListenerConfig.
	SocketReceiveBuffer int

	// SocketSendBuffer is the SO_SNDBUF size, in bytes, requested for the
	// association's SCTP socket: RFC 6458 Section 8.1.7 has it control "the
	// amount of data SCTP may have waiting in internal buffers to be sent".
	// Linux goes on charging DATA against it after sending it, until the peer
	// acknowledges it. Zero leaves the size the socket starts with, as for
	// SocketReceiveBuffer.
	//
	// Linux caps the request at net.core.wmem_max and then doubles it, as
	// socket(7) describes, even where net.core.wmem_default is the larger;
	// Association.SocketSendBuffer reports the size that took effect.
	SocketSendBuffer int
}

// DefaultInitTimeout bounds one SCTP association attempt: how long Dial waits
// for the INIT-ACK before giving up and releasing the socket.
//
// Dial makes at most one attempt and never retries; a caller that wants to keep
// trying loops over Dial and chooses its own cadence. Left to the kernel, the
// attempt runs to net.sctp.max_init_retransmits with the RTO doubling from
// net.sctp.rto_initial to net.sctp.rto_max — measured at nine INIT chunks over
// 342 seconds on Linux defaults, which is far too long for an application to
// react to anything.
//
// Dial enforces the one-shot contract per socket by raising SCTP_RTOINFO's
// Initial and Max values beyond this budget before connecting. If no INIT-ACK
// arrives before the timeout, Dial returns ErrInitTimeout; if ctx is cancelled
// first, Dial quietly abandons the in-flight socket promptly and returns
// ctx.Err().
const DefaultInitTimeout = 5 * time.Second

// DefaultEstablishTimeout bounds the M3UA handshake once the association is up:
// how long Dial and Accept wait to reach ASP-ACTIVE.
const DefaultEstablishTimeout = 10 * time.Second

// DefaultControlWriteTimeout bounds how long a message the library writes on its
// own behalf may wait for SCTP send-buffer space; see
// AssociationConfig.ControlWriteTimeout.
//
// A full send buffer is ordinary transport behaviour, not a failure: it lasts
// until the peer opens its receive window or a lost DATA chunk is retransmitted.
// RFC 9260 Section 16 recommends RTO.Min = 1 second and Section 6.3.3 rule E2
// doubles the RTO on each T3-rtx expiry, so two consecutive expiries of the same
// chunk hold the buffer for about 1 + 2 = 3 seconds. Five seconds absorbs that
// with margin while staying below DefaultEstablishTimeout and the T(ack) budget
// of DefaultTAck times one more than DefaultTAckRetries, the time within which a
// peer has to complete an ASP procedure.
const DefaultControlWriteTimeout = 5 * time.Second

// DefaultDataQueueSize is the number of inbound DATA messages one association
// retains while its application is not reading. It is large enough to absorb
// ordinary traffic bursts without the 65,535-slot allocation every Association used
// to make; sustained overflow remains non-blocking and reports local congestion.
const DefaultDataQueueSize = 1024

// DefaultRecoveryQueueMessages bounds how many outbound DATA messages an SGP
// retains while an Application Server is AS-PENDING. RFC 4666 Section 4.3.2
// recommends queuing during T(r), but an unbounded queue lets a failed AS
// exhaust the process before recovery can complete.
const DefaultRecoveryQueueMessages = 1024

// DefaultRecoveryQueueBytes bounds the encoded size of the DATA messages held
// for one AS during T(r). The count limit alone is insufficient because M3UA
// deliberately permits payloads larger than an SS7 MTP2 SIF.
const DefaultRecoveryQueueBytes = 4 << 20

// DefaultRecoveryQueueTotalMessages bounds recovery DATA retained across all
// Application Servers owned by one SGP Endpoint.
const DefaultRecoveryQueueTotalMessages = 4096

// DefaultRecoveryQueueTotalBytes is the SGP Endpoint-wide encoded DATA budget.
const DefaultRecoveryQueueTotalBytes = 16 << 20

// DefaultBroadcastFlowCacheEntries bounds synchronization markers retained for
// one Broadcast AS. Eviction can only cause an extra Correlation ID to be sent.
const DefaultBroadcastFlowCacheEntries = 4096

// DefaultBroadcastFlowIdentifierBytes bounds the application-defined portion
// of a retained Broadcast flow key.
const DefaultBroadcastFlowIdentifierBytes = 256

// DefaultTAckRetries is how many times an unacknowledged ASPSM/ASPTM request is
// resent before the attempt is reported as failed.
//
// RFC 4666 says to resend "until it receives an ASP Up Ack message", and the
// same for ASP Down, ASP Active and ASP Inactive, which is unbounded; a bound
// turns a peer that will never answer into a reportable error instead of an
// indefinite silent retry against a network already in trouble.
const DefaultTAckRetries = 5

// BroadcastFlowIdentifier adds application semantics to the default Broadcast
// traffic-flow key. The library already keys by Network Appearance, Routing
// Context, and the complete MTP3 routing label. Applications may return, for
// example, an ISUP CIC or SCCP subsystem discriminator when independently
// sequenced flows share that label. The callback receives an owned copy and
// must return a stable identifier for equivalent flows.
type BroadcastFlowIdentifier func(*params.ProtocolDataPayload) (string, error)

// ASActivationPolicy configures the n+k activation threshold of one
// Application Server.
//
// RFC 4666 Sections 1.4.4.1 and 4.3.2 define RequiredActiveASPs as n. Zero
// selects one. SmoothStart enables the Section 4.3.2 exception that permits
// the first active ASP to start traffic before n ASPs are active.
type ASActivationPolicy struct {
	RequiredActiveASPs int
	SmoothStart        bool
}

func (p ASActivationPolicy) requiredActive() int {
	if p.RequiredActiveASPs == 0 {
		return 1
	}
	return p.RequiredActiveASPs
}

// ApplicationServerConfig configures Application Server state shared by all
// Associations owned by one SGP or IPSP Endpoint.
type ApplicationServerConfig struct {
	// RecoveryTimer is T(r), the AS-PENDING recovery timer of RFC 4666
	// Section 4.3.2. Zero selects DefaultRecoveryTimer.
	RecoveryTimer time.Duration
	// DefaultActivationPolicy applies when ActivationPolicies has no exact
	// ASKey entry.
	DefaultActivationPolicy ASActivationPolicy
	// ActivationPolicies configures n and smooth start for exact Application
	// Server traffic identities. The map is deeply copied by NewEndpoint.
	ActivationPolicies map[ASKey]ASActivationPolicy
}

// SGPConfig configures protocol state shared by every Association owned by one
// Signalling Gateway Process Endpoint.
//
// RFC 4666 Sections 4.3.2, 4.3.4.3, and 4.6 define recovery queuing,
// distribution, and restart procedures in terms of an SGP and its Application
// Servers, not in terms of one SCTP association or the peer that initiated it.
type SGPConfig struct {
	// RecoveryQueueMessages and RecoveryQueueBytes bound DATA retained for one
	// AS while T(r) runs. Values less than or equal to zero select defaults.
	RecoveryQueueMessages int
	RecoveryQueueBytes    int
	// RecoveryQueueTotalMessages and RecoveryQueueTotalBytes bound retained DATA
	// across every AS owned by the SGP Endpoint.
	RecoveryQueueTotalMessages int
	RecoveryQueueTotalBytes    int
	// BroadcastFlowIdentifier refines the default routing-label flow key used
	// for RFC 4666 Section 4.3.4.3 Broadcast synchronization Correlation IDs.
	BroadcastFlowIdentifier BroadcastFlowIdentifier
	// BroadcastFlowCacheEntries bounds remembered flows per AS. Values less than
	// or equal to zero select DefaultBroadcastFlowCacheEntries.
	BroadcastFlowCacheEntries int
	// BroadcastFlowIdentifierBytes bounds an application-defined flow
	// identifier. Values less than or equal to zero select the default.
	BroadcastFlowIdentifierBytes int
	// MaxSSNMDestinationRecords bounds the destination records retained by the
	// SGP Endpoint and by each Listener it owns. A peer cannot drive this store,
	// but a large provisioned network can, so it is configurable. Values less
	// than or equal to zero select DefaultMaxSSNMDestinationRecords.
	MaxSSNMDestinationRecords int
}

// IPSPExchangeModel identifies the peer-to-peer exchange model used by one
// IPSP Association. RFC 4666 Section 4.3 defines Single Exchange and Double
// Exchange independently of which IPSP initiates the SCTP association.
type IPSPExchangeModel uint8

const (
	// IPSPExchangeSingle is the mandatory Single Exchange model of RFC 4666
	// Sections 4.3 and 5.6.1. One ASPSM or ASPTM request-and-ack exchange
	// changes the state maintained by both IPSPs.
	IPSPExchangeSingle IPSPExchangeModel = iota + 1
	// IPSPExchangeDouble is the optional Double Exchange model of RFC 4666
	// Sections 4.3 and 5.6.2. Its independent directional state is implemented
	// separately from Single Exchange.
	IPSPExchangeDouble
)

// IPSPASPSMExchangeModel identifies the ASPSM procedure agreed for an IPSP
// Double Exchange Association. RFC 4666 Section 4.3 defines the normal double
// exchange and permits a single exchange as an agreed simplification.
type IPSPASPSMExchangeModel uint8

const (
	// IPSPASPSMExchangeDouble keeps the two IPSP ASPSM directions independent.
	IPSPASPSMExchangeDouble IPSPASPSMExchangeModel = iota + 1
	// IPSPASPSMExchangeSingle lets one ASP Up or ASP Down exchange affect the
	// whole IPSP communication, as permitted by RFC 4666 Sections 4.3 and 5.6.2.
	IPSPASPSMExchangeSingle
)

// IPSPTrafficConfig configures one direction of IPSP Double Exchange traffic.
//
// ApplicationServers is that direction's own Application Server inventory and
// the only thing the direction declares. RFC 4666 Section 5.6.2 keeps the two
// directions of a Double Exchange independent, so neither reads the other's
// membership, Network Appearance or Traffic Mode.
//
// A nil IPSPTrafficConfig is no traffic in that direction at all. A non-nil one
// with an empty inventory is the contextless Application Server of Section
// 3.6.1 in that direction, exactly as it is on an Association.
type IPSPTrafficConfig struct {
	ApplicationServers []ASConfig
}

// IPSPConfig configures RFC 4666 peer-to-peer procedures for one Association.
//
// Which procedures this IPSP starts is AssociationConfig.ASPProcedures, which
// an IPSP Association must set: either IPSP may initiate each exchange, the
// choices are independent of SCTP association initiation, and there is no
// role-implied default to fall back on.
type IPSPConfig struct {
	ExchangeModel IPSPExchangeModel
	// ASPSMExchange is the ASPSM agreement for Double Exchange. It is not
	// used by Single Exchange.
	ASPSMExchange IPSPASPSMExchangeModel
	// TrafficToLocal configures DATA the peer sends to this IPSP.
	TrafficToLocal *IPSPTrafficConfig
	// TrafficToPeer configures DATA this IPSP sends to the peer.
	TrafficToPeer *IPSPTrafficConfig
}

// EndpointConfig gives one M3UA Endpoint its immutable RFC 4666 role and any
// role-specific node policy.
type EndpointConfig struct {
	Role                 Role
	ASP                  *ASPConfig
	SGP                  *SGPConfig
	ApplicationServers   *ApplicationServerConfig
	RoutingKeyManagement *RoutingKeyManagementConfig
	// SSNMState bounds the route-independent SSNM state store. It applies to
	// every role: an SGP retains what it publishes and what its peers report
	// about themselves exactly as an ASP retains what its Signalling Gateways
	// report. A nil configuration selects the package defaults.
	SSNMState *SSNMStateConfig
}

func validateApplicationServerConfig(config *ApplicationServerConfig) error {
	if config == nil {
		return nil
	}
	if config.RecoveryTimer < 0 {
		return fmt.Errorf("%w: negative RecoveryTimer", ErrInvalidApplicationServerConfig)
	}
	if config.DefaultActivationPolicy.RequiredActiveASPs < 0 {
		return fmt.Errorf("%w: negative default RequiredActiveASPs", ErrInvalidApplicationServerConfig)
	}
	for key, policy := range config.ActivationPolicies {
		if !key.NetworkAppearanceSet && key.NetworkAppearance != 0 {
			return fmt.Errorf("%w: Network Appearance %d is present without NetworkAppearanceSet",
				ErrInvalidApplicationServerConfig, key.NetworkAppearance)
		}
		if !key.RoutingContextSet && key.RoutingContext != 0 {
			return fmt.Errorf("%w: Routing Context %d is present without RoutingContextSet",
				ErrInvalidApplicationServerConfig, key.RoutingContext)
		}
		if policy.RequiredActiveASPs < 0 {
			return fmt.Errorf("%w: negative RequiredActiveASPs for %+v",
				ErrInvalidApplicationServerConfig, key)
		}
	}
	return nil
}

func snapshotApplicationServerConfig(config *ApplicationServerConfig) *ApplicationServerConfig {
	if config == nil {
		return &ApplicationServerConfig{}
	}
	snapshot := *config
	if config.ActivationPolicies != nil {
		snapshot.ActivationPolicies = make(map[ASKey]ASActivationPolicy, len(config.ActivationPolicies))
		for key, policy := range config.ActivationPolicies {
			snapshot.ActivationPolicies[key] = policy
		}
	}
	return &snapshot
}

func applicationServerActivationPolicy(config *ApplicationServerConfig, key ASKey) ASActivationPolicy {
	if config == nil {
		return ASActivationPolicy{}
	}
	if policy, ok := config.ActivationPolicies[key]; ok {
		return policy
	}
	return config.DefaultActivationPolicy
}

func validateApplicationServerRoutingKeyPolicies(
	applicationServers *ApplicationServerConfig,
	routingKeys *RoutingKeyManagementConfig,
) error {
	if routingKeys == nil {
		return nil
	}
	for _, provisioned := range routingKeys.ProvisionedRoutingKeys {
		if !provisioned.RoutingKey.TrafficModeSet ||
			provisioned.RoutingKey.TrafficMode != params.TrafficModeOverride {
			continue
		}
		key := ASKey{
			NetworkAppearance:    provisioned.RoutingKey.NetworkAppearance,
			NetworkAppearanceSet: provisioned.RoutingKey.NetworkAppearanceSet,
			RoutingContext:       provisioned.RoutingContext,
			RoutingContextSet:    true,
		}
		if applicationServerActivationPolicy(applicationServers, key).requiredActive() != 1 {
			return fmt.Errorf("%w: Override requires one active ASP for %+v",
				ErrInvalidApplicationServerConfig, key)
		}
	}
	return nil
}

func snapshotSGPConfig(config *SGPConfig) *SGPConfig {
	if config == nil {
		return &SGPConfig{}
	}
	snapshot := *config
	return &snapshot
}

// ASPIdentity identifies an ASP at the point its ASP Up is received. The ASP
// Identifier is optional in RFC 4666, so ASPIdentifierSet distinguishes an
// omitted identifier from the valid value zero. RemoteAddr is nil for an Association
// constructed without a live SCTP association.
type ASPIdentity struct {
	ASPIdentifier    uint32
	ASPIdentifierSet bool
	RemoteAddr       net.Addr
}

// ASPAuthorizer returns the Routing Contexts an accepted ASP is configured to
// serve. The result is copied and must be a subset of the Routing Contexts
// named by AssociationConfig.ApplicationServers.
// Returning an empty slice authorizes no Application Server. The decision is
// resolved once at ASP Up and remains immutable for that association.
type ASPAuthorizer func(ASPIdentity) []uint32

// ASConfig declares one Application Server an Association carries.
//
// ASKey is the exact scope that names it on this Association's wire. RFC 4666
// Section 3.3.1 makes the Network Appearance "of local significance only,
// coordinated between the SGP and ASP", and Section 1.4.2.1 makes a Routing
// Context "an index into a sending node's Message Distribution Table", so the
// pair identifies the Application Server and the Routing Context alone does
// not. That pair is what a DataRequest names and what a received message is
// resolved against.
//
// An ASKey without a Routing Context is the contextless Application Server of
// Section 3.6.1, the one an SGP serving a single Routing Key needs no Routing
// Context for. An Association may declare at most one, and not beside
// Routing-Context-scoped ones: a message that omitted the Routing Context would
// otherwise name both.
//
// TrafficMode is the Section 3.7.1 Traffic Mode Type agreed for this one
// Application Server. The table there defines 1 Override, 2 Loadshare and 3
// Broadcast and nothing else, so zero leaves the mode unconfigured and the
// peer's requested mode stands.
type ASConfig struct {
	ASKey       ASKey
	TrafficMode uint32
}

// AssociationConfig configures one M3UA association.
//
// A Listener owns the shared SCTP listening socket; each accepted SCTP
// association uses an immutable AssociationConfig snapshot selected by
// ListenerConfig before any M3UA message is parsed.
type AssociationConfig struct {
	// HeartbeatInfo controls M3UA BEAT/BEAT Ack liveness only; it is separate
	// from SCTP HEARTBEAT path management.
	*HeartbeatInfo
	*SCTPConfig
	// TAck is the T(ack) timer: how long to wait for an ASPSM/ASPTM
	// acknowledgement before resending the request. Zero selects DefaultTAck
	// (2 seconds, per RFC 4666 Sections 4.3.4.1 to 4.3.4.4).
	TAck time.Duration
	// TAckRetries bounds how many times a request is resent before the attempt
	// is reported as failed. Every send, the last resend included, is given
	// TAck to be answered, so an unanswered request fails TAck x (TAckRetries
	// + 1) after it was first sent. Zero selects DefaultTAckRetries.
	TAckRetries int
	// EstablishTimeout bounds the M3UA handshake once the association is up.
	// Zero selects DefaultEstablishTimeout.
	EstablishTimeout time.Duration
	// ControlWriteTimeout bounds how long a message the library writes on its
	// own behalf may wait for SCTP send-buffer space: acknowledgements, BEAT
	// and BEAT Ack, Error, Notify, destination state replies and publications,
	// registration responses, ASP procedure requests and their T(ack)
	// retransmissions. Such a message waits while the buffer is full rather
	// than failing; if it is still waiting when the bound expires, the
	// association is closed with ErrControlWriteTimeout, because a peer that
	// cannot absorb mandatory control traffic can no longer run the protocol.
	// Values less than or equal to zero select DefaultControlWriteTimeout.
	//
	// A socket write deadline set with Association.SetWriteDeadline supersedes
	// this bound: while one is in force, a library write waits only until the
	// deadline.
	//
	// The Endpoint's destination state publications are the library's writes
	// and wait. Writes the application asks for on one Association do not:
	// WriteData, WriteSignal, DestinationStateAudit, SignallingCongestion,
	// RegisterRoutingKeys and DeregisterApplicationServers report a full send
	// buffer to the caller; see WriteSignal.
	ControlWriteTimeout time.Duration
	// DataQueueSize is the maximum number of inbound DATA messages retained for
	// ReadData. Values less than or equal to zero select
	// DefaultDataQueueSize. Once full, further DATA is discarded and local
	// congestion is reported without blocking the association dispatcher.
	DataQueueSize int
	ASPIdentifier *params.Param
	// AuthorizeASP optionally narrows this accepted Association's configured
	// Routing Context inventory to the immutable set its peer ASP may serve.
	// Without it, the peer ASP may serve every configured Routing Context.
	AuthorizeASP ASPAuthorizer
	// Compatibility configures explicit receive-side tolerance for known peer
	// protocol violations. The zero value keeps RFC-strict behaviour.
	Compatibility CompatibilityPolicy
	// ASPProcedures selects automatic or explicit Layer Management initiation
	// for ASP Up, ASP Down, ASP Active, and ASP Inactive. A nil policy preserves
	// the historical role-specific lifecycle. A non-nil policy fully supersedes
	// IPSPConfig.InitiateASPSM and IPSPConfig.InitiateASPTM.
	ASPProcedures *ASPProcedurePolicy
	// PeerSGP identifies the remote Signalling Gateway Process for an
	// Association owned by an ASP Endpoint. It is invalid for an SGP Endpoint.
	PeerSGP *SGPIdentity
	// IPSP is required for an Association owned by an IPSP Endpoint and invalid
	// for ASP and SGP Endpoints. The exchange model is Association policy: one
	// IPSP may use different models with different peers.
	IPSP *IPSPConfig

	// ApplicationServers is the Application Server inventory this Association
	// carries. It is the whole of the Association's membership: each entry
	// names one Application Server by the exact ASKey a DataRequest must name,
	// and carries the Traffic Mode agreed for that one Application Server.
	//
	// An empty inventory is the contextless Application Server of RFC 4666
	// Section 3.6.1 with no Network Appearance and no agreed Traffic Mode.
	// Declaring that Application Server explicitly is how it is given either.
	ApplicationServers []ASConfig
}

// AcceptInfo identifies an SCTP association before its M3UA handshake starts.
//
// The addresses are owned copies of the SCTP addresses returned by the
// association so a selector can inspect or retain full multi-homing data
// without mutating transport-owned address objects.
type AcceptInfo struct {
	LocalAddr  *sctp.SCTPAddr
	RemoteAddr *sctp.SCTPAddr
}

// AssociationConfigSelector chooses the immutable AssociationConfig for an
// accepted SCTP association.
type AssociationConfigSelector func(AcceptInfo) (*AssociationConfig, error)

// ListenerConfig configures a shared M3UA listener.
//
// DefaultAssociationConfig is the fallback per-association configuration. If
// SelectAssociationConfig is set, it runs after SCTP accept and before socket
// options, monitor goroutines, ASP Up parsing, or compatibility handling.
//
// DefaultAssociationConfig also sizes the listening socket, whether or not
// SelectAssociationConfig is set: its SCTPConfig.SocketReceiveBuffer and
// SocketSendBuffer are applied before listen, and every accepted association
// inherits them. The sizes are fixed when Listen is called; changing the
// default afterwards resizes nothing.
//
// An accepted association's receive size can therefore only come from
// DefaultAssociationConfig, and a selector cannot raise it. That holds for a
// Listener configured with a selector alone as well, whose default from
// NewListenerConfig(nil) leaves the kernel's size. The INIT ACK has announced
// the receive window by the time SelectAssociationConfig runs, so a selected
// SocketReceiveBuffer must be zero or the default's own. Any other value
// refuses that association with ErrInvalidSCTPConfig once its SCTP association
// is up, and the Listener carries on serving.
//
// Applying a different size to the accepted socket could not honour it, because
// Linux keeps the window it announced. A larger buffer would give the peer no
// more window, and would hold back the window updates that reopen it: Linux
// sends one only once the window has grown by the larger of the path MTU and
// the socket buffer shifted right by net.sctp.rwnd_update_shift, 4 by default
// (sctp_peer_needs_update in net/sctp/associola.c). A 32 MiB buffer behind the
// 106,496-octet window a 212,992-byte default announces would wait for 2 MiB of
// growth, more than the whole window. A smaller buffer would leave the peer
// entitled to more than it holds, which is the overflow the setting exists to
// prevent and what RFC 9260 Sections 3.3.2 and 3.3.3 advise against: "During
// the life of the association, this buffer space SHOULD NOT be reduced". A peer
// that needs a different receive size needs a Listener of its own.
//
// A selected SocketSendBuffer is announced to no one, so a non-zero one is
// applied to the accepted socket exactly.
type ListenerConfig struct {
	DefaultAssociationConfig *AssociationConfig
	SelectAssociationConfig  AssociationConfigSelector
}

// NewListenerConfig creates a listener configuration with an immutable default
// AssociationConfig snapshot.
func NewListenerConfig(defaultAssociationConfig *AssociationConfig) *ListenerConfig {
	if defaultAssociationConfig == nil {
		defaultAssociationConfig = NewAssociationConfig()
	}
	return &ListenerConfig{
		DefaultAssociationConfig: snapshotAssociationConfig(defaultAssociationConfig),
	}
}

func (l *ListenerConfig) associationConfigForAccept(info AcceptInfo) (*AssociationConfig, error) {
	if l == nil {
		return nil, errors.New("nil ListenerConfig")
	}
	selected := l.DefaultAssociationConfig
	if l.SelectAssociationConfig != nil {
		var err error
		selected, err = l.SelectAssociationConfig(info)
		if err != nil {
			return nil, err
		}
	}
	if selected == nil {
		return nil, errors.New("nil AssociationConfig")
	}
	return snapshotAssociationConfig(selected), nil
}

func snapshotAssociationConfig(config *AssociationConfig) *AssociationConfig {
	if config == nil {
		return nil
	}
	snapshot := *config
	if config.HeartbeatInfo != nil {
		heartbeat := *config.HeartbeatInfo
		snapshot.HeartbeatInfo = &heartbeat
	}
	if config.SCTPConfig != nil {
		sctpConfig := *config.SCTPConfig
		if config.SCTPConfig.SCTPSACKInfo != nil {
			sack := *config.SCTPConfig.SCTPSACKInfo
			sctpConfig.SCTPSACKInfo = &sack
		}
		if config.SCTPConfig.SCTPNoDelayInfo != nil {
			noDelay := *config.SCTPConfig.SCTPNoDelayInfo
			sctpConfig.SCTPNoDelayInfo = &noDelay
		}
		snapshot.SCTPConfig = &sctpConfig
	} else {
		snapshot.SCTPConfig = &SCTPConfig{}
	}
	snapshot.ASPIdentifier = config.ASPIdentifier.Copy()
	snapshot.ApplicationServers = snapshotApplicationServers(config.ApplicationServers)
	if config.ASPProcedures != nil {
		procedures := *config.ASPProcedures
		snapshot.ASPProcedures = &procedures
	}
	if config.PeerSGP != nil {
		peerSGP := *config.PeerSGP
		snapshot.PeerSGP = &peerSGP
	}
	if config.IPSP != nil {
		ipsp := *config.IPSP
		ipsp.TrafficToLocal = snapshotIPSPTrafficConfig(config.IPSP.TrafficToLocal)
		ipsp.TrafficToPeer = snapshotIPSPTrafficConfig(config.IPSP.TrafficToPeer)
		snapshot.IPSP = &ipsp
	}
	return &snapshot
}

// snapshotApplicationServers copies an Application Server inventory. The
// public AssociationConfig may be reused and mutated by its owner, so the
// protocol goroutines must never read the caller's slice.
func snapshotApplicationServers(servers []ASConfig) []ASConfig {
	if servers == nil {
		return nil
	}
	return append(make([]ASConfig, 0, len(servers)), servers...)
}

func validateAssociationConfigForRole(role Role, config *AssociationConfig) error {
	if config == nil {
		return ErrNilAssociationConfig
	}
	if err := validateSCTPConfig(config.SCTPConfig); err != nil {
		return err
	}
	if err := validateApplicationServers("ApplicationServers", config.ApplicationServers); err != nil {
		return err
	}
	if err := validateASPProcedurePolicy(role, config.ASPProcedures); err != nil {
		return err
	}
	switch role {
	case RoleASP:
		if config.IPSP != nil {
			return fmt.Errorf("%w: IPSP applies only to an IPSP", ErrInvalidRoleConfiguration)
		}
		if config.AuthorizeASP != nil {
			return fmt.Errorf("%w: AuthorizeASP applies only to an SGP", ErrInvalidRoleConfiguration)
		}
	case RoleSGP:
		if config.IPSP != nil {
			return fmt.Errorf("%w: IPSP applies only to an IPSP", ErrInvalidRoleConfiguration)
		}
		if config.ASPIdentifier != nil {
			return fmt.Errorf("%w: ASPIdentifier applies only to an ASP", ErrInvalidRoleConfiguration)
		}
		if config.PeerSGP != nil {
			return fmt.Errorf("%w: PeerSGP applies only to an ASP", ErrInvalidRoleConfiguration)
		}
	case RoleIPSP:
		if config.IPSP == nil {
			return fmt.Errorf("%w: IPSP requires an explicit exchange model", ErrInvalidRoleConfiguration)
		}
		if config.ASPProcedures == nil {
			return fmt.Errorf("%w: IPSP requires an explicit ASP procedure policy", ErrInvalidRoleConfiguration)
		}
		if config.AuthorizeASP != nil {
			return fmt.Errorf("%w: AuthorizeASP applies only to an SGP", ErrInvalidRoleConfiguration)
		}
		if config.PeerSGP != nil {
			return fmt.Errorf("%w: PeerSGP applies only to an ASP", ErrInvalidRoleConfiguration)
		}
		switch config.IPSP.ExchangeModel {
		case IPSPExchangeSingle:
			if config.IPSP.ASPSMExchange != 0 || config.IPSP.TrafficToLocal != nil || config.IPSP.TrafficToPeer != nil {
				return fmt.Errorf("%w: IPSP Single Exchange uses the Association traffic configuration", ErrInvalidRoleConfiguration)
			}
			return nil
		case IPSPExchangeDouble:
			if config.IPSP.ASPSMExchange != IPSPASPSMExchangeDouble &&
				config.IPSP.ASPSMExchange != IPSPASPSMExchangeSingle {
				return fmt.Errorf("%w: IPSP Double Exchange requires an explicit ASPSM exchange agreement", ErrInvalidRoleConfiguration)
			}
			if config.IPSP.TrafficToLocal == nil && config.IPSP.TrafficToPeer == nil {
				return fmt.Errorf("%w: IPSP Double Exchange requires at least one traffic direction", ErrInvalidRoleConfiguration)
			}
			automaticASPSM := config.ASPProcedures.ASPUp == ASPProcedureAutomatic
			automaticASPTM := config.ASPProcedures.ASPActive == ASPProcedureAutomatic
			if config.IPSP.ASPSMExchange == IPSPASPSMExchangeDouble &&
				automaticASPSM && config.IPSP.TrafficToLocal == nil {
				return fmt.Errorf("%w: normal Double Exchange ASPSM initiation requires TrafficToLocal", ErrInvalidRoleConfiguration)
			}
			if automaticASPTM && config.IPSP.TrafficToLocal == nil {
				return fmt.Errorf("%w: automatic ASP Active requires TrafficToLocal", ErrInvalidRoleConfiguration)
			}
			if len(config.ApplicationServers) != 0 {
				return fmt.Errorf("%w: IPSP Double Exchange traffic policy must be directional", ErrInvalidRoleConfiguration)
			}
			if err := validateIPSPTrafficConfig("TrafficToLocal", config.IPSP.TrafficToLocal); err != nil {
				return err
			}
			if err := validateIPSPTrafficConfig("TrafficToPeer", config.IPSP.TrafficToPeer); err != nil {
				return err
			}
			return nil
		default:
			return fmt.Errorf("%w: exchange model %d", ErrUnsupportedIPSPExchangeModel, config.IPSP.ExchangeModel)
		}
	default:
		return ErrUnsupportedRole
	}
	return nil
}

func validateIPSPTrafficConfig(name string, config *IPSPTrafficConfig) error {
	if config == nil {
		return nil
	}
	return validateApplicationServers(name+".ApplicationServers", config.ApplicationServers)
}

// validateApplicationServers rejects an Application Server inventory that
// names one Application Server twice, that could name two at once, or that
// carries a Traffic Mode RFC 4666 Section 3.7.1 does not define.
//
// The presence flags are load bearing: zero is a legitimate explicit value for
// either half of an ASKey, so a value left behind without its flag would make
// two equal scopes compare unequal and is refused rather than normalized.
func validateApplicationServers(name string, servers []ASConfig) error {
	seen := make(map[ASKey]struct{}, len(servers))
	contextless := false
	routingContextScoped := false
	for _, server := range servers {
		key := server.ASKey
		if !key.NetworkAppearanceSet && key.NetworkAppearance != 0 {
			return fmt.Errorf("%w: %s Network Appearance %d is present without NetworkAppearanceSet",
				ErrInvalidApplicationServerConfig, name, key.NetworkAppearance)
		}
		if !key.RoutingContextSet && key.RoutingContext != 0 {
			return fmt.Errorf("%w: %s Routing Context %d is present without RoutingContextSet",
				ErrInvalidApplicationServerConfig, name, key.RoutingContext)
		}
		if server.TrafficMode != 0 && !validTrafficMode(server.TrafficMode) {
			return fmt.Errorf("%w: %s has undefined Traffic Mode %d for %+v",
				ErrInvalidApplicationServerConfig, name, server.TrafficMode, key)
		}
		if _, duplicate := seen[key]; duplicate {
			return fmt.Errorf("%w: %s names %+v twice",
				ErrInvalidApplicationServerConfig, name, key)
		}
		seen[key] = struct{}{}
		if key.RoutingContextSet {
			routingContextScoped = true
			continue
		}
		if contextless {
			return fmt.Errorf("%w: %s declares more than one contextless Application Server",
				ErrInvalidApplicationServerConfig, name)
		}
		contextless = true
		if !key.NetworkAppearanceSet && server.TrafficMode == 0 {
			// An entry that names nothing is the empty inventory written a
			// second way, and two spellings of one membership can drift apart.
			return fmt.Errorf("%w: %s declares a contextless Application Server with no Network Appearance "+
				"and no Traffic Mode; omit the entry instead",
				ErrInvalidApplicationServerConfig, name)
		}
	}
	if contextless && routingContextScoped {
		// RFC 4666 Section 3.3.1 lets a message omit the Routing Context only
		// "where a Routing Key has not been coordinated". With one coordinated,
		// an omitted Routing Context would name the contextless Application
		// Server and the coordinated ones alike.
		return fmt.Errorf("%w: %s declares a contextless Application Server beside Routing-Context-scoped ones",
			ErrInvalidApplicationServerConfig, name)
	}
	return nil
}

func snapshotIPSPTrafficConfig(config *IPSPTrafficConfig) *IPSPTrafficConfig {
	if config == nil {
		return nil
	}
	snapshot := *config
	snapshot.ApplicationServers = snapshotApplicationServers(config.ApplicationServers)
	return &snapshot
}

func newAcceptInfo(local, remote net.Addr) AcceptInfo {
	return AcceptInfo{
		LocalAddr:  cloneSCTPAddrFromNetAddr(local),
		RemoteAddr: cloneSCTPAddrFromNetAddr(remote),
	}
}

func cloneSCTPAddrFromNetAddr(addr net.Addr) *sctp.SCTPAddr {
	sctpAddr, ok := addr.(*sctp.SCTPAddr)
	if !ok {
		return nil
	}
	return cloneSCTPAddr(sctpAddr)
}

func cloneSCTPAddr(addr *sctp.SCTPAddr) *sctp.SCTPAddr {
	if addr == nil {
		return nil
	}
	clone := &sctp.SCTPAddr{Port: addr.Port}
	if len(addr.IPAddrs) > 0 {
		clone.IPAddrs = make([]net.IPAddr, len(addr.IPAddrs))
		for index, ipAddr := range addr.IPAddrs {
			clone.IPAddrs[index] = net.IPAddr{
				IP:   append(net.IP(nil), ipAddr.IP...),
				Zone: ipAddr.Zone,
			}
		}
	}
	return clone
}

// NewAssociationConfig creates a role-neutral M3UA association configuration.
//
// It takes no message defaults. Every DATA message carries its own MTP3 routing
// label, Application Server scope and Correlation Id in its DataRequest, as RFC
// 4666 Section 3.3.1 defines them, so there is nothing about a message for an
// association to hold. Use the setters below, or the exported fields, for the
// policy that genuinely belongs to the association.
func NewAssociationConfig() *AssociationConfig {
	return &AssociationConfig{SCTPConfig: &SCTPConfig{}}
}

// EnableHeartbeat enables RFC 4666 M3UA BEAT with the given interval and
// expiration timer.
//
// It does not enable, disable, or tune SCTP HEARTBEAT chunks; SCTP heartbeat
// behavior remains transport/kernel behavior.
//
// Each BEAT carries freshly generated random Heartbeat Data, and the BEAT
// Ack's echo is validated against it, so BEAT/BEAT Ack pairs identify
// themselves and a replayed Ack is rejected.
func (c *AssociationConfig) EnableHeartbeat(interval, timer time.Duration) *AssociationConfig {
	c.HeartbeatInfo = NewHeartbeatInfo(interval, timer)
	return c
}

// SetSCTPSACK sets the SCTP SACK timer configuration.
//
// sackDelay is the number of milliseconds for the delayed SACK timer. RFC 9260
// Section 6.2 allows any value up to 500 ms and forbids more. This setter is
// chainable and has no way to report that, so a larger value is refused when
// the association is set up, and Dial or Accept fails with ErrSackDelayTooLarge.
//
// sackFrequency is the number of packets to receive before sending a SACK
// without waiting for the delay timer. Setting to 1 disables the delayed
// SACK algorithm.
//
// Note: sackDelay=0, sackFrequency=1 (disables delayed SACK)
func (c *AssociationConfig) SetSCTPSACK(sackDelay, sackFrequency uint32) *AssociationConfig {
	if c.SCTPConfig == nil {
		c.SCTPConfig = &SCTPConfig{}
	}
	c.SCTPConfig.SCTPSACKInfo = &SCTPSACKInfo{
		Enabled:       true,
		SackDelay:     sackDelay,
		SackFrequency: sackFrequency,
	}
	return c
}

// SetSCTPNoDelay sets the SCTP_NODELAY option.
//
// When noDelay is true, the Nagle-like bundling algorithm is disabled and
// user messages are sent as soon as possible. When false, small messages
// may be bundled to improve throughput.
func (c *AssociationConfig) SetSCTPNoDelay(noDelay bool) *AssociationConfig {
	if c.SCTPConfig == nil {
		c.SCTPConfig = &SCTPConfig{}
	}
	c.SCTPConfig.SCTPNoDelayInfo = &SCTPNoDelayInfo{
		Enabled: true,
		NoDelay: noDelay,
	}
	return c
}

// SetASPIdentifier sets the optional RFC 4666 ASP Identifier parameter.
func (c *AssociationConfig) SetASPIdentifier(id uint32) *AssociationConfig {
	c.ASPIdentifier = params.NewAspIdentifier(id)
	return c
}

// SetApplicationServers replaces the Application Server inventory this
// Association carries. Passing none leaves the contextless Application Server
// of RFC 4666 Section 3.6.1 with no Network Appearance and no agreed Traffic
// Mode.
func (c *AssociationConfig) SetApplicationServers(servers ...ASConfig) *AssociationConfig {
	c.ApplicationServers = snapshotApplicationServers(servers)
	return c
}
